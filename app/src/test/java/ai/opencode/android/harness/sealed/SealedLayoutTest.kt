package ai.opencode.android.harness.sealed

import java.io.File
import java.nio.file.Files
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

/**
 * The manifest parser and the symlink applier, tested on a real filesystem.
 *
 * Everything in the sealed design reduces to "this absolute prefix path is a
 * symlink whose target is inside the APK's native library directory", so the
 * parser's safety rules (no absolute paths, no `..`) and the applier's refusal
 * to invent or clobber are load-bearing, not cosmetic.
 */
class SealedLayoutTest {

    @get:Rule
    val tmp = TemporaryFolder()

    private val nativeDir: File by lazy { tmp.newFolder("native") }

    private fun lib(name: String): File {
        val file = File(nativeDir, name)
        file.writeBytes(byteArrayOf(0x7f, 'E'.code.toByte(), 'L'.code.toByte(), 'F'.code.toByte(), 0x02))
        return file
    }

    @Test
    fun parse_skipsCommentsAndBlankLines() {
        val links = SealedLayout.parse(
            "# generated by the build\n" +
                "\n" +
                "bin/bash\tlibbash.so\n" +
                "  \n" +
                "bin/git\tlibgit.so\n"
        )
        assertEquals(2, links.size)
        assertEquals("bin/bash", links[0].path)
        assertEquals("libbash.so", links[0].library)
        assertEquals("bin/git", links[1].path)
    }

    @Test
    fun parse_acceptsSpacesAndStripsDotSlash() {
        val links = SealedLayout.parse("./bin/git libgit.so\nbin/sh\tlibsh.so\n")
        assertEquals(listOf("bin/git", "bin/sh"), links.map { it.path })
    }

    @Test
    fun parse_rejectsEscapingPaths() {
        val links = SealedLayout.parse(
            "/etc/passwd\tlibpasswd.so\n" +
                "../../outside\tliboutside.so\n" +
                "bin/git\tlibgit.so\n"
        )
        assertEquals(listOf("bin/git"), links.map { it.path })
    }

    @Test
    fun parse_rejectsMalformedLines() {
        assertTrue(SealedLayout.parse("nonsense\n").isEmpty())
        assertTrue(SealedLayout.parse("\tjust-a-library.so\n").isEmpty())
        assertTrue(SealedLayout.parse("just-a-path\t\n").isEmpty())
        assertTrue(SealedLayout.parse(null).isEmpty())
    }

    @Test
    fun apply_linksExecutablesIntoTheApk() {
        lib("libgit.so")
        val prefix = tmp.newFolder("prefix")
        val result = SealedLayout.apply(
            prefix,
            nativeDir,
            listOf(SealedLayout.Link("bin/git", "libgit.so"))
        )

        assertTrue(result.summary(), result.ok())
        assertEquals(1, result.linked)
        val linked = File(prefix, "bin/git")
        assertTrue(Files.isSymbolicLink(linked.toPath()))
        assertEquals(lib("libgit.so").absolutePath, SealedLinks.readLink(linked))
    }

    @Test
    fun apply_isIdempotent() {
        lib("libgit.so")
        val prefix = tmp.newFolder("prefix")
        val nativeDir = nativeDir
        val links = listOf(SealedLayout.Link("bin/git", "libgit.so"))

        val first = SealedLayout.apply(prefix, nativeDir, links)
        val second = SealedLayout.apply(prefix, nativeDir, links)

        assertEquals(1, first.linked)
        assertEquals(0, second.linked)
        assertEquals(1, second.alreadyCorrect)
    }

    @Test
    fun apply_upgradeAddsToolsMissingFromAnOlderInstalledPrefix() {
        lib("libgit.so")
        lib("libnode.so")
        lib("libpython3.so")
        val prefix = tmp.newFolder("prefix")
        val nativeDir = nativeDir

        val oldInstall = SealedLayout.apply(
            prefix,
            nativeDir,
            listOf(SealedLayout.Link("bin/git", "libgit.so")),
        )
        assertTrue(oldInstall.summary(), oldInstall.ok())
        assertTrue(!File(prefix, "bin/node").exists())
        assertTrue(!File(prefix, "bin/python3").exists())

        // Startup reads the current APK manifest every time; applying a newer
        // manifest to persisted app data must add the new executable links
        // instead of treating the old prefix as already complete.
        val upgraded = SealedLayout.apply(
            prefix,
            nativeDir,
            listOf(
                SealedLayout.Link("bin/git", "libgit.so"),
                SealedLayout.Link("bin/node", "libnode.so"),
                SealedLayout.Link("bin/python3", "libpython3.so"),
            ),
        )
        assertTrue(upgraded.summary(), upgraded.ok())
        assertEquals(2, upgraded.linked)
        assertEquals(1, upgraded.alreadyCorrect)
        assertEquals(lib("libnode.so").absolutePath, SealedLinks.readLink(File(prefix, "bin/node")))
        assertEquals(lib("libpython3.so").absolutePath, SealedLinks.readLink(File(prefix, "bin/python3")))
    }

    @Test
    fun apply_rewritesALinkThatPointsSomewhereElse() {
        lib("libgit.so")
        lib("libgit2.so")
        val prefix = tmp.newFolder("prefix")
        val nativeDir = nativeDir

        SealedLayout.apply(prefix, nativeDir, listOf(SealedLayout.Link("bin/git", "libgit2.so")))
        val replaced = SealedLayout.apply(prefix, nativeDir, listOf(SealedLayout.Link("bin/git", "libgit.so")))

        assertEquals(1, replaced.linked)
        assertEquals(lib("libgit.so").absolutePath, SealedLinks.readLink(File(prefix, "bin/git")))
    }

    @Test
    fun apply_reportsAMissingLibraryInsteadOfLeavingTheOldBinary() {
        val prefix = tmp.newFolder("prefix")
        val stale = File(prefix, "bin/git")
        stale.parentFile?.mkdirs()
        stale.writeBytes(byteArrayOf(0x7f, 'E'.code.toByte(), 'L'.code.toByte(), 'F'.code.toByte()))

        val result = SealedLayout.apply(
            prefix,
            tmp.newFolder("native"),
            listOf(SealedLayout.Link("bin/git", "libgit.so"))
        )

        assertEquals(1, result.missingTargets.size)
        assertTrue(result.missingTargets[0].contains("libgit.so"))
        // The stale binary is left alone: removing it would silently turn a
        // packaging bug into "no git at all" with no record of why.
        assertTrue(stale.isFile)
    }

    @Test
    fun apply_refusesToReplaceADirectory() {
        lib("libgit.so")
        val prefix = tmp.newFolder("prefix")
        File(prefix, "bin/git").mkdirs()

        val result = SealedLayout.apply(
            prefix,
            nativeDir,
            listOf(SealedLayout.Link("bin/git", "libgit.so"))
        )

        assertEquals(1, result.errors.size)
        assertTrue(result.errors[0].contains("refusing to replace directory"))
        assertTrue(File(prefix, "bin/git").isDirectory)
    }

    @Test
    fun apply_withoutPrefixOrLibDirReportsIt() {
        val result = SealedLayout.apply(null, null, emptyList())
        assertTrue(result.errors.any { it.contains("prefix or lib dir missing") })
    }

    @Test
    fun readManifest_returnsNullWhenAbsent() {
        assertNull(SealedLayout.readManifest(File(tmp.root, "nope.txt")))
        assertNull(SealedLayout.readManifest(null))
    }

    @Test
    fun toMap_preservesOrder() {
        val links = SealedLayout.parse("bin/zsh\tlibzsh.so\nbin/bash\tlibbash.so\n")
        assertEquals(listOf("bin/zsh", "bin/bash"), SealedLayout.toMap(links).keys.toList())
    }
}
